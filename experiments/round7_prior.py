"""Disclosed post-hoc architecture-affinity diagnostics for the journal revision.

Uses only fixed, already validation-selected 128-pixel checkpoints and validation
images. All four datasets therefore have the same 8x8 token grid. This analysis
cannot identify a causal data moderator or supply clinical validation.

    $PY -m experiments.round7_prior freeze
    $PY -m experiments.round7_prior run --device cuda:1
"""
from __future__ import annotations

import argparse
import gc
import json
import time
from pathlib import Path

import numpy as np
import pandas as pd
import torch
from torch.utils.data import DataLoader, Subset

from .common import CLASSES, MEAN, ROOT, STD, ManifestDataset, build_model, load_manifest, seed_all, sha256, write_json
from .round3 import external_data
from .round6 import transform128

OUT = ROOT / 'results/round7/prior'
PROTOCOL = ROOT / 'configs/round7_prior_protocol.json'
DATASETS = ['canine128', 'bloodmnist128', 'octmnist128', 'dermamnist_c128']
SEEDS = [42, 43, 44]
BLOCKS = [0, 5, 11]
PER_CLASS = 64
SAMPLE_SEED = 20261109
RELATIVE_SVD_CUTOFF = 1e-8
SOURCES = ['experiments/round7_prior.py', 'experiments/common.py', 'experiments/round3.py',
           'experiments/round6.py', 'models/psan.py', 'models/gfnet.py']


def run_directory(dataset, arm, seed):
    base = ROOT / ('results/round6/grid128/final' if dataset == 'canine128' else 'results/round3/external/final')
    candidates = sorted(base.glob(f'{dataset}_{arm}_c[0-9]_s{seed}_final'))
    if len(candidates) != 1:
        raise ValueError(f'Expected exactly one selected final: {dataset}, {arm}, {seed}: {candidates}')
    return candidates[0]


def protocol_spec():
    checkpoints = {}
    for dataset in DATASETS:
        for seed in SEEDS:
            for arm in ['psan', 'gfnet_matched']:
                directory = run_directory(dataset, arm, seed)
                checkpoint = directory / 'best.pth'
                summary = json.loads((directory / 'summary.json').read_text())
                digest = sha256(checkpoint)
                if digest != summary['checkpoint_sha256']:
                    raise ValueError(f'Existing checkpoint hash mismatch: {checkpoint}')
                checkpoints[f'{dataset}/{arm}/{seed}'] = dict(
                    checkpoint=str(checkpoint.relative_to(ROOT)), sha256=digest,
                    config_sha256=sha256(directory / 'config.json'),
                    summary_sha256=sha256(directory / 'summary.json'))
    return dict(
        protocol='round7_validation_spectra_filter_affinity_v1', frozen_on='2026-11-09',
        post_hoc=True, not_a_blinded_holdout=True,
        motivation='Reviewer1.1: describe the limits and quantitative correlates of the dataset-dependent prior benefit.',
        prior_exposure='All submitted canine and MedMNIST+ performance results were known before specifying this analysis.',
        inference_scope='validation images only; no new training, no test-image inference, no outcome-based metric selection',
        datasets=DATASETS, seeds=SEEDS, image_size=128, token_grid=[8, 8], atoms=16,
        class_sampling=dict(per_class_maximum=PER_CLASS, seed=SAMPLE_SEED,
                            procedure='Within each class, fixed random permutation and retain up to64 validation images.',
                            summary='Equal weight to each class, then equal weight to each model seed; not natural prevalence.'),
        token_blocks=BLOCKS, batch_size=64,
        spectra=dict(
            input='RGB restored to [0,1] from normalized model inputs, 128x128; per-channel spatial mean removed for non-DC metrics.',
            token='Inputs to the matched-dense or PSAN filter after norm1; full orthonormal FFT over token positions.',
            dc_fraction='Power in (0,0) divided by total power, summed over channels.',
            low_non_dc_fraction='Non-DC power at radial frequency <=0.5 of Nyquist, divided by all non-DC power.',
            centroid_non_dc='Power-weighted radial frequency / Nyquist after removing DC; diagonal frequencies may exceed1.',
            entropy_non_dc='Shannon entropy over non-DC frequency bins normalized by log(number of bins).'),
        filter_diagnostics=dict(
            stored_rank16='Relative squared Frobenius residual of optimal complex rank16 approximation to D x40 stored coefficients.',
            effective='Project DC/Nyquist columns onto Hermitian symmetry, then expand the full 8x8 multiplier.',
            roughness='Sum of squared differences to each circular adjacent frequency in both axes, divided by2 times total filter power.',
            operator_rank32='Optimal real rank32 residual after concatenating real/imaginary parts of the effective full multiplier.',
            atom_projection='Exact least-squares projection onto the16 complex atom rows; effective-operator projection uses32 real rows generated by psi and i*psi.',
            bases='Same-dataset same-seed trained PSAN bank versus untrained Morlet bank; no atom fitting to dense filters.',
            svd_relative_cutoff=RELATIVE_SVD_CUTOFF,
            interpretation='Affinity to a learned architectural basis; not a raw-data cause and not cross-model feature equivalence.'),
        reporting='All datasets/seeds/blocks and controls, means and descriptive seed SD; no significance/regression over four domains.',
        split_sha256=sha256(ROOT / 'results/revision_split.csv'), checkpoints=checkpoints,
        source_code_sha256={p: sha256(ROOT / p) for p in SOURCES})


def freeze():
    spec = protocol_spec()
    if PROTOCOL.exists() and json.loads(PROTOCOL.read_text()) != spec:
        raise ValueError('Frozen prior protocol differs; use a new version instead of overwriting.')
    if not PROTOCOL.exists():
        write_json(PROTOCOL, spec)
    return spec


def effective_full(k, width):
    """Effective Hermitian multiplier of a stored rFFT filter, (..., H, W//2+1)."""
    result = k.clone()
    h = result.shape[-2]
    opposite = (-torch.arange(h, device=k.device)) % h
    boundaries = [0, width // 2] if width % 2 == 0 else [0]
    for v in boundaries:
        column = result[..., :, v].clone()
        result[..., :, v] = (column + column[..., opposite].conj()) * .5
    full = torch.empty((*result.shape[:-1], width), dtype=k.dtype, device=k.device)
    full[..., :width // 2 + 1] = result
    for v in range(width // 2 + 1, width):
        full[..., :, v] = result[..., opposite, width - v].conj()
    return full


def row_projection_residual(target, basis):
    """Squared relative residual, computed with the actual numerical row span."""
    _, s, vh = torch.linalg.svd(basis, full_matrices=False)
    rank = int((s > s[0] * RELATIVE_SVD_CUTOFF).sum()) if len(s) and s[0] > 0 else 0
    rows = vh[:rank]
    projected = (target @ rows.mH) @ rows
    denom = target.abs().square().sum().clamp_min(1e-30)
    return float((target - projected).abs().square().sum() / denom), rank


def rank_residual(matrix, rank):
    s = torch.linalg.svdvals(matrix)
    return float(s[rank:].square().sum() / s.square().sum().clamp_min(1e-30))


def spectrum_metrics(x):
    """Per-image full-spectrum summaries; input shape B,H,W,C, real-valued."""
    x = x.to(torch.float64)
    spectrum = torch.fft.fft2(x, dim=(1, 2), norm='ortho')
    power = spectrum.abs().square().sum(-1)
    h, w = x.shape[1:3]
    u = torch.fft.fftfreq(h, device=x.device, dtype=x.dtype)
    v = torch.fft.fftfreq(w, device=x.device, dtype=x.dtype)
    radius = torch.sqrt(u[:, None].square() + v[None, :].square()) / .5
    total = power.sum((1, 2)).clamp_min(1e-30)
    dc = power[:, 0, 0] / total
    non = power.clone(); non[:, 0, 0] = 0
    non_total = non.sum((1, 2)).clamp_min(1e-30)
    p = non / non_total[:, None, None]
    return dict(
        dc_fraction=dc.detach().cpu().numpy(),
        low_non_dc_fraction=(non[:, radius <= .5].sum(1) / non_total).detach().cpu().numpy(),
        centroid_non_dc=(p * radius).sum((1, 2)).detach().cpu().numpy(),
        entropy_non_dc=(-(p * p.clamp_min(1e-300).log()).sum((1, 2)) / np.log(h * w - 1)).detach().cpu().numpy())


def filter_metrics(dense, atom_filter, initialized):
    k = torch.complex(dense.filter_real, dense.filter_imag).permute(2, 0, 1).to(torch.complex128).cpu()
    h, wh = k.shape[-2:]; width = (wh - 1) * 2
    full = effective_full(k, width)
    total = full.abs().square().sum().clamp_min(1e-30)
    roughness = sum((full - full.roll(1, axis)).abs().square().sum() for axis in [-2, -1]) / (2 * total)
    real_operator = torch.cat([full.real.flatten(1), full.imag.flatten(1)], 1)
    row = dict(stored_rank16_residual=rank_residual(k.flatten(1), 16),
               effective_rank32_residual=rank_residual(real_operator, 32),
               effective_roughness=float(roughness))
    for label, module in [('learned', atom_filter), ('initialized', initialized)]:
        re, im = module._atoms_complex()
        psi = torch.complex(re, im).to(torch.complex128).cpu()
        residual, rank = row_projection_residual(k.flatten(1), psi.flatten(1))
        row[f'{label}_stored_projection_residual'] = residual
        row[f'{label}_stored_basis_rank'] = rank
        basis = effective_full(torch.cat([psi, 1j * psi]), width)
        real_basis = torch.cat([basis.real.flatten(1), basis.imag.flatten(1)], 1)
        residual, rank = row_projection_residual(real_operator, real_basis)
        row[f'{label}_operator_projection_residual'] = residual
        row[f'{label}_operator_basis_rank'] = rank
    return row


def load_checkpoint(directory, device):
    cfg = json.loads((directory / 'config.json').read_text())
    checkpoint = torch.load(directory / 'best.pth', map_location='cpu', weights_only=False)
    model = build_model(cfg['model'], classes=cfg['num_classes'], size=cfg['img_size'],
                        dropout=cfg.get('atom_dropout') or 0., atoms=cfg.get('atoms') or 16)
    model.load_state_dict(checkpoint['eval_model'], strict=True)
    return model.to(device).eval(), cfg


def validation_data(dataset):
    if dataset == 'canine128':
        frame = load_manifest(); frame = frame[frame.split == 'val'].reset_index(drop=True)
        data = ManifestDataset(frame, False, 224)
        data.transform = transform128(False)
        classes = CLASSES
    else:
        frames, data_map, classes, _, _ = external_data(dataset, ['val'])
        frame, data = frames['val'], data_map['val']
    rng = np.random.default_rng(SAMPLE_SEED)
    indices = []
    for label in sorted(frame.label.unique()):
        ids = np.flatnonzero(frame.label.to_numpy() == label)
        indices.extend(rng.permutation(ids)[:PER_CLASS].tolist())
    frame = frame.iloc[indices].reset_index(drop=True)
    frame['class_name'] = [classes[y] for y in frame.label]
    data = Subset(data, indices)
    loader = DataLoader(data, batch_size=64, shuffle=False, num_workers=2)
    inputs = torch.cat([x for x, _ in loader])
    return frame, inputs


def class_macro(frame, columns):
    return frame.groupby('label', observed=True)[columns].mean().mean().to_dict()


def run(device_name):
    spec = json.loads(PROTOCOL.read_text())
    if spec != protocol_spec():
        raise ValueError('Source or fixed artifacts changed since freeze.')
    OUT.mkdir(parents=True, exist_ok=True)
    seed_all(SAMPLE_SEED)
    torch.set_num_threads(4)
    device = torch.device(device_name)
    if device.type == 'cuda':
        torch.cuda.set_device(device)
    filter_rows, feature_rows, summary_rows, input_rows = [], [], [], []
    started = time.time()
    metric_names = ['dc_fraction', 'low_non_dc_fraction', 'centroid_non_dc', 'entropy_non_dc']
    for dataset in DATASETS:
        frame, inputs = validation_data(dataset)
        frame.to_csv(OUT / f'{dataset}_validation_sample.csv', index=False)
        rgb = inputs * torch.tensor(STD)[None, :, None, None] + torch.tensor(MEAN)[None, :, None, None]
        raw = spectrum_metrics(rgb.permute(0, 2, 3, 1))
        raw_frame = frame[['path', 'label', 'group_id', 'class_name']].copy()
        for key, value in raw.items(): raw_frame[key] = value
        raw_frame['dataset'] = dataset
        input_rows.append(raw_frame)
        input_summary = class_macro(raw_frame, metric_names)
        for seed in SEEDS:
            dense, dense_cfg = load_checkpoint(run_directory(dataset, 'gfnet_matched', seed), device)
            psan, psan_cfg = load_checkpoint(run_directory(dataset, 'psan', seed), device)
            with torch.random.fork_rng(devices=[]):
                torch.manual_seed(seed)
                initialized = build_model('psan', classes=dense_cfg['num_classes'], size=128).eval()
            for b, (db, pb, ib) in enumerate(zip(dense.blocks, psan.blocks, initialized.blocks)):
                with torch.no_grad():
                    row = filter_metrics(db.filter, pb.filter, ib.filter)
                filter_rows.append(dict(dataset=dataset, seed=seed, block=b, **row))
            for arm, model in [('gfnet_matched', dense), ('psan', psan)]:
                accum = {b: {k: [] for k in metric_names} for b in BLOCKS}
                handles = []
                for b in BLOCKS:
                    def hook(module, args, block=b):
                        for key, val in spectrum_metrics(args[0]).items(): accum[block][key].append(val)
                    handles.append(model.blocks[b].filter.register_forward_pre_hook(hook))
                with torch.inference_mode():
                    for batch in inputs.split(64): model(batch.to(device))
                for h in handles: h.remove()
                for b in BLOCKS:
                    values = frame[['path', 'label', 'group_id', 'class_name']].copy()
                    for key in metric_names: values[key] = np.concatenate(accum[b][key])
                    values['dataset'], values['seed'], values['arm'], values['block'] = dataset, seed, arm, b
                    feature_rows.append(values)
                    summary_rows.append(dict(dataset=dataset, seed=seed, arm=arm, block=b,
                                             samples=len(frame), **class_macro(values, metric_names)))
            del dense, psan, initialized
            gc.collect()
            if device.type == 'cuda': torch.cuda.empty_cache()
            print(f'{dataset} seed={seed} samples={len(frame)} elapsed={time.time()-started:.1f}s', flush=True)
        write_json(OUT / f'{dataset}_input_summary.json', dict(
            dataset=dataset, samples=len(frame), classes=int(frame.label.nunique()),
            natural_validation_counts='See original split; the present sample and summaries weight classes equally.',
            sample_sha256=sha256(OUT / f'{dataset}_validation_sample.csv'), **input_summary))
    filters = pd.DataFrame(filter_rows)
    filters.to_csv(OUT / 'filter_per_block.csv', index=False)
    filter_columns = [c for c in filters if c not in ['dataset', 'seed', 'block']]
    per_seed = filters.groupby(['dataset', 'seed'], as_index=False)[filter_columns].mean()
    per_seed.to_csv(OUT / 'filter_per_seed.csv', index=False)
    pd.concat(input_rows).to_csv(OUT / 'input_per_image.csv.gz', index=False)
    pd.concat(feature_rows).to_csv(OUT / 'token_per_image.csv.gz', index=False)
    pd.DataFrame(summary_rows).to_csv(OUT / 'token_per_seed_block.csv', index=False)
    write_json(OUT / 'provenance.json', dict(
        protocol_sha256=sha256(PROTOCOL), source_code_sha256=spec['source_code_sha256'],
        checkpoints=spec['checkpoints'], device=device_name, elapsed_sec=time.time()-started,
        datasets=DATASETS, seeds=SEEDS, test_images_used=False,
        interpretation='Post-hoc descriptive architecture-affinity diagnostics, not causal data-property or clinical validation.',
        output_sha256={p.name: sha256(p) for p in sorted(OUT.iterdir()) if p.is_file() and p.name != 'provenance.json'}))
    print(per_seed.groupby('dataset')[filter_columns].mean().to_string(), flush=True)


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('command', choices=['freeze', 'run'])
    parser.add_argument('--device', default='cuda:1')
    args = parser.parse_args()
    if args.command == 'freeze':
        freeze(); print(PROTOCOL)
    else:
        run(args.device)


if __name__ == '__main__':
    main()

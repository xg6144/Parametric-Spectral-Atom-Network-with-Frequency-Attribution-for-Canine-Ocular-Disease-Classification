"""Generic low-rank spectral filters used as controls for PSAN (round 4, 2026-10-14).

`LowRankFilter` factorizes the dense complex filter as K = W B with a free basis
B in C^(M x h x (w//2+1)) and mixing weights W in C^(D x M). It shares the rank bound
rank(K) <= M and the exact per-component decomposition of PSAN, but its basis is
unconstrained instead of being generated by eight-parameter Gaussian/Gabor atoms.
The FFT convention, layout and complex arithmetic follow `PSANFilter` exactly.
"""
import torch
import torch.nn as nn

from .psan import PSANConfig, PSANFilter


class LowRankFilter(nn.Module):
    def __init__(self, dim, h, w, M, basis_real, basis_imag, w_real, w_imag):
        super().__init__()
        self.dim, self.h, self.w, self.M = dim, h, w, M
        if basis_real.shape != (M, h, w // 2 + 1) or w_real.shape != (dim, M):
            raise ValueError('Low-rank filter tensors have inconsistent shapes')
        self.basis_real = nn.Parameter(basis_real.detach().clone())
        self.basis_imag = nn.Parameter(basis_imag.detach().clone())
        self.w_real = nn.Parameter(w_real.detach().clone())
        self.w_imag = nn.Parameter(w_imag.detach().clone())

    @classmethod
    def from_psan(cls, psan_filter):
        """Start from the initial atoms and mixing weights of a PSAN filter, so that the
        initial filter, and hence the initial network function, is identical."""
        cfg = psan_filter.cfg
        with torch.no_grad():
            psi_re, psi_im = psan_filter._atoms_complex()
        return cls(cfg.dim, cfg.h, cfg.w, cfg.M, psi_re, psi_im, psan_filter.w_real, psan_filter.w_imag)

    def build_filter(self):
        """K in C^(D, h, w//2+1) = sum_m w_{:, m} b_m."""
        M, D = self.M, self.dim
        K_re = self.w_real @ self.basis_real.reshape(M, -1) - self.w_imag @ self.basis_imag.reshape(M, -1)
        K_im = self.w_real @ self.basis_imag.reshape(M, -1) + self.w_imag @ self.basis_real.reshape(M, -1)
        shape = (D, self.h, self.w // 2 + 1)
        return torch.complex(K_re.reshape(shape), K_im.reshape(shape))

    def forward(self, x):
        """x: (B, H, W, D)."""
        B, H, W, D = x.shape
        assert (H, W, D) == (self.h, self.w, self.dim)
        X = torch.fft.rfft2(x, dim=(1, 2), norm='ortho')
        K = self.build_filter().permute(1, 2, 0)
        return torch.fft.irfft2(X * K, s=(H, W), dim=(1, 2), norm='ortho')


GEOMETRY = ('mu', 'log_sigma', 'rho_raw', 'theta', 'log_amp', 'phi')


def to_low_rank(model, atoms):
    """Replace every PSAN filter of `model` by a free rank-`atoms` factorization.

    With atoms equal to the PSAN bank size, the basis starts from the model's own initial
    atoms. Otherwise a Morlet-initialized PSAN filter with `atoms` atoms is constructed for
    each block (consuming the random stream only for its mixing weights) and used as start.
    """
    for block in model.blocks:
        source = block.filter
        if not isinstance(source, PSANFilter):
            raise TypeError('Expected a PSAN backbone')
        if atoms != source.cfg.M:
            cfg = source.cfg
            source = PSANFilter(PSANConfig(dim=cfg.dim, h=cfg.h, w=cfg.w, M=atoms, atom=cfg.atom, init=cfg.init,
                                           anisotropic=cfg.anisotropic, learn_phase=cfg.learn_phase,
                                           atom_dropout=0.))
        block.filter = LowRankFilter.from_psan(source)
    return model


def freeze_atom_geometry(model):
    """Keep the initial atom geometry fixed; only the complex mixing weights are learned."""
    frozen = 0
    for block in model.blocks:
        for name in GEOMETRY:
            parameter = getattr(block.filter, name)
            if isinstance(parameter, nn.Parameter):
                parameter.requires_grad_(False)
                frozen += parameter.numel()
    return frozen
